function cleanEnglishBusinessText(value: string): string {
  return ENGLISH_BUSINESS_TEXT_REPLACEMENTS.reduce(
    (text, item) => text.replace(item.pattern, item.replacement),
    value,
  )
    .replace(/没Yes/g, 'no')
    .replace(/Yes人/g, 'anyone')
    .replace(/所Yes/g, 'all')
    .replace(/Yes价值/g, 'valuable')
    .replace(/Yes明显/g, 'clear')
    .replace(/Yes/g, 'has')
    .replace(/亲and型/g, 'Amiable')
    .replace(/All客户/g, 'All accounts')
    .replace(/All来源/g, 'All sources')
    .replace(/AllUrgent度/g, 'All urgency levels')
    .replace(/Todayno安排/g, 'No schedule today')
    .replace(/Company名称/g, 'Company name')
    .replace(/(\d+)人/g, '$1 people')
    .replace(/(\d+)个/g, '$1 ')
    .replace(/technical reviewagenda/g, 'technical review agenda')
    .replace(/ROIexecutive/g, 'ROI executive')
    .replace(/evidenceReview/g, 'evidence. Review')
    .replace(/evidenceKey/g, 'evidence. Key')
    .replace(/Play假设not validated/g, 'Play assumptions are not validated')
    .replace(/\s+([,.;:!?])/g, '$1')
    .replace(/([([{])\s+/g, '$1')
    .replace(/\s+([)\]}])/g, '$1')
    .replace(/\s{2,}/g, ' ')
    .trim();
}

function cleanChineseBusinessText(value: string): string {
  return BUSINESS_TEXT_REPLACEMENTS.reduce(
    (text, item) => text.replace(item.pattern, item.replacement),
    value,
  )
    .replace(/自研\s+自研平台/g, '自研平台')
    .replace(/([\u4e00-\u9fff])\s+([\u4e00-\u9fff])/g, '$1$2');
}

export function visibleBusinessText(value?: string | null, locale?: ProductLocale): string {
  if (!value) return '';
  return normalizeProductLocale(locale) === 'en'
    ? cleanEnglishBusinessText(value)
    : cleanChineseBusinessText(value);
}
