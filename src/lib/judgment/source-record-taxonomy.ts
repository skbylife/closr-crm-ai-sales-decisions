export type SourceRecordKind = keyof typeof SOURCE_RECORD_KIND_DEFINITIONS;

const SOURCE_RECORD_KIND_SET = new Set<string>(Object.keys(SOURCE_RECORD_KIND_DEFINITIONS));

const NON_AUTHORITATIVE_JUDGMENT_SOURCE_TABLES = new Set(['ai_insights']);

export function isAllowedSourceRecordKind(kind: unknown): kind is SourceRecordKind {
  return typeof kind === 'string' && SOURCE_RECORD_KIND_SET.has(kind);
}

export function getSourceRecordKindDefinition(kind: SourceRecordKind): SourceRecordKindDefinition {
  return SOURCE_RECORD_KIND_DEFINITIONS[kind];
}

export function assertAllowedSourceRecordKinds(kinds: readonly string[], context: string): void {
  const unknownKinds = kinds.filter((kind) => !isAllowedSourceRecordKind(kind));
  if (unknownKinds.length > 0) {
    throw new Error(`${context} uses unsupported source_records.source_kind: ${unknownKinds.join(', ')}`);
  }
}

export function isAuthoritativeJudgmentSource(input: { sourceKind?: string | null; sourceTable?: string | null }): boolean {
  if (input.sourceTable && NON_AUTHORITATIVE_JUDGMENT_SOURCE_TABLES.has(input.sourceTable)) return false;
  if (!input.sourceKind) return false;
  const definition = isAllowedSourceRecordKind(input.sourceKind)
    ? getSourceRecordKindDefinition(input.sourceKind)
    : null;
  return definition?.authority === 'authoritative_trace';
}

