'use client';

import { visibleBusinessText } from "@/lib/visible-business-text";
import { useLocale } from "@/lib/i18n";
import { useState, useMemo, Suspense, useEffect, useRef } from 'react';
import { Send, Sparkles, Loader2, Copy, Check, Mail } from 'lucide-react';
import { useStore } from '@/lib/store';
import { useSearchParams } from 'next/navigation';
import { SocialIntentPanel } from '@/components/decode/social-intent-panel';
import { buildComposeSocialIntentSummary, type SocialIntentSummary } from '@/lib/babel-engine/social-intent';
const EMAIL_TYPES = [{
  value: 'cold_outreach',
  label: '首次接触'
}, {
  value: 'follow_up',
  label: '跟进'
}, {
  value: 'meeting_invite',
  label: '会议邀请'
}, {
  value: 'proposal_send',
  label: '方案发送'
}, {
  value: 'quote_follow_up',
  label: '报价跟进'
}, {
  value: 'holiday_greeting',
  label: '节日问候'
}, {
  value: 'reactivation',
  label: '重新激活'
}, {
  value: 'custom',
  label: '自定义'
}];
function ComposeInner() {
  const {
    locale
  } = useLocale();
  const en = locale === "en";
  const tx = (value: string) => en ? visibleBusinessText(value, "en") : value;
  const accounts = useStore(s => s.accounts);
  const searchParams = useSearchParams();
  const [toEmail, setToEmail] = useState(searchParams.get('to') || '');
  const [toName, setToName] = useState(searchParams.get('name') || '');
  const [toTitle, setToTitle] = useState(searchParams.get('title') || '');
  const [accountId, setAccountId] = useState(searchParams.get('accountId') || '');
  const [contactId, setContactId] = useState(searchParams.get('contactId') || '');
  const [subject, setSubject] = useState('');
  const initialDraft = searchParams.get('draft') || searchParams.get('context') || '';
  const [body, setBody] = useState(initialDraft);
  const [emailType, setEmailType] = useState(searchParams.get('emailType') || 'follow_up');
  const [emailGoal, setEmailGoal] = useState(searchParams.get('goal') || '');
  const [aiDrafting, setAiDrafting] = useState(false);
  const [sendingAdvice, setSendingAdvice] = useState('');
  const [generatedSocialIntent, setGeneratedSocialIntent] = useState<SocialIntentSummary | null>(null);
  const [generatedBodySnapshot, setGeneratedBodySnapshot] = useState('');
  const [copied, setCopied] = useState(false);
  const [sent, setSent] = useState(false);
  const autoGeneratedRef = useRef(false);

  // Flatten contacts for quick-pick
  const allContacts = useMemo(() => accounts.flatMap(a => (a.contacts || []).map(c => ({
    ...c,
    accountName: a.name,
    accountId: a.id
  }))), [accounts]);

  // Find selected contact's profile for richer AI context
  const selectedContact = useMemo(() => {
    if (!contactId) return null;
    return allContacts.find(c => c.id === contactId) ?? null;
  }, [allContacts, contactId]);
  const socialIntent = useMemo(() => {
    if (!body.trim()) return null;
    if (generatedSocialIntent && generatedBodySnapshot === body) return generatedSocialIntent;
    return buildComposeSocialIntentSummary({
      body,
      emailGoal,
      emailType,
      sendingAdvice,
      contactTitle: toTitle || selectedContact?.title || undefined,
      contactRole: selectedContact?.role || undefined,
      contactProfile: selectedContact?.contactProfile ? JSON.stringify(selectedContact.contactProfile).slice(0, 2000) : undefined
    });
  }, [body, emailGoal, emailType, generatedBodySnapshot, generatedSocialIntent, selectedContact, sendingAdvice, toTitle]);

  // AI draft via compose-email API
  const handleAIDraft = async () => {
    if (!toName) return;
    setAiDrafting(true);
    setSendingAdvice('');
    try {
      const res = await fetch('/api/compose-email', {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json'
        },
        body: JSON.stringify({
          contactName: toName,
          contactTitle: toTitle || selectedContact?.title || undefined,
          contactRole: selectedContact?.role || undefined,
          emailType,
          emailGoal: emailGoal || '跟进合作事宜',
          additionalContext: body || undefined,
          contactProfile: selectedContact?.contactProfile ? JSON.stringify(selectedContact.contactProfile).slice(0, 2000) : undefined
        })
      });
      const data = await res.json();
      if (data.subject) setSubject(data.subject);
      if (data.body) {
        setBody(data.body);
        setGeneratedBodySnapshot(data.body);
      }
      if (data.sendingAdvice) setSendingAdvice(data.sendingAdvice);
      setGeneratedSocialIntent(data.socialIntent ?? null);
    } catch {/* ignore */}
    setAiDrafting(false);
  };
  useEffect(() => {
    if (autoGeneratedRef.current) return;
    if (searchParams.get('autoGenerate') !== '1') return;
    if (!toName) return;
    autoGeneratedRef.current = true;
    void handleAIDraft();
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [searchParams, toName]);

  // Copy to clipboard
  const handleCopy = () => {
    const text = `To: ${toEmail}\nSubject: ${subject}\n\n${body}`;
    navigator.clipboard.writeText(text);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  // Log activity + mark sent
  const handleSend = async () => {
    if (!toEmail || !body) return;
    handleCopy();
    await fetch('/api/log-activity', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json'
      },
      body: JSON.stringify({
        accountId: accountId || undefined,
        contactId: contactId || undefined,
        contactName: toName || undefined,
        actionType: 'email_sent',
        entityType: 'contact',
        entityId: contactId || undefined,
        entityName: toName || undefined,
        summary: `发送邮件: ${subject} → ${toName || toEmail}`,
        metadata: {
          to: toEmail,
          subject
        }
      })
    }).catch(err => console.error('[compose] 邮件发送活动日志失败:', err));
    setSent(true);
  };

  // Quick-pick a contact
  const handleSelectContact = (contact: typeof allContacts[0]) => {
    setToEmail(contact.email || '');
    setToName(contact.name);
    setToTitle(contact.title || '');
    setAccountId(contact.accountId);
    setContactId(contact.id);
  };
  if (sent) {
    return <div className="mx-auto max-w-3xl px-3 py-4 sm:px-6 sm:py-6">
        <div className="rounded-xl border border-positive/20 bg-positive/5 p-8 text-center">
          <Check className="mx-auto h-12 w-12 text-positive mb-4" />
          <p className="text-lg font-bold text-foreground">{tx("邮件已记录")}</p>
          <p className="text-sm text-muted mt-2">{tx("邮件内容已复制到剪贴板，请在邮件客户端粘贴发送")}</p>
          <p className="text-xs text-muted mt-1">{tx("活动已自动记录到客户时间线")}</p>
          <div className="mt-4 flex justify-center gap-3">
            <button onClick={() => {
            setSent(false);
            setBody('');
            setSubject('');
            setSendingAdvice('');
            setGeneratedSocialIntent(null);
            setGeneratedBodySnapshot('');
          }} className="rounded-lg border border-border px-4 py-2 text-sm text-foreground hover:bg-background">{tx("撰写新邮件")}</button>
            <a href={accountId ? `/accounts/${accountId}` : '/accounts'} className="rounded-lg bg-accent px-4 py-2 text-sm font-semibold text-white hover:bg-accent-hover">{tx("返回客户")}</a>
          </div>
        </div>
      </div>;
  }
  return <div className="mx-auto max-w-3xl space-y-4 px-3 py-4 sm:px-6 sm:py-6">
      {/* Header */}
      <div>
        <h1 className="text-xl font-bold text-foreground sm:text-2xl">
          <Mail className="mr-2 inline-block h-5 w-5 sm:h-6 sm:w-6" />{tx("写信")}</h1>
        <p className="text-sm text-muted mt-1">{tx("智能辅助撰写，基于联系人画像定制沟通风格")}</p>
      </div>

      {/* Recipient */}
      <div className="rounded-xl border border-border bg-card p-4 space-y-3">
        <div>
          <label className="text-[12px] text-muted font-medium">{tx("收件人")}</label>
          <div className="flex gap-2 mt-1">
            <input type="email" value={toEmail} onChange={e => setToEmail(e.target.value)} placeholder="email@example.com" className="form-input flex-1" />
            {toName && <span className="rounded-lg bg-accent/10 px-3 py-1.5 text-xs text-accent font-medium self-center">
                {toName}
              </span>}
          </div>
          {/* Quick-pick contacts */}
          {!toEmail && allContacts.length > 0 && <div className="mt-2 flex flex-wrap gap-1.5">
              {allContacts.filter(c => c.email).slice(0, 8).map(c => <button key={c.id} onClick={() => handleSelectContact(c)} className="rounded-full border border-border px-2.5 py-1 text-[12px] text-secondary hover:text-foreground hover:border-accent/30">
                  {c.name} · {c.accountName}
                </button>)}
            </div>}
        </div>

        <div>
          <label className="text-[12px] text-muted font-medium">{tx("主题")}</label>
          <input type="text" value={subject} onChange={e => setSubject(e.target.value)} placeholder={tx("邮件主题（AI 可自动生成）")} className="form-input mt-1 w-full" />
        </div>
      </div>

      {/* AI controls */}
      <div className="flex flex-wrap items-center gap-2 sm:gap-3">
        <select value={emailType} onChange={e => setEmailType(e.target.value)} className="rounded-lg border border-border bg-card px-3 py-1.5 text-xs w-full sm:w-auto">
          {EMAIL_TYPES.map(et => <option key={et.value} value={et.value}>{et.label}</option>)}
        </select>
        <input type="text" value={emailGoal} onChange={e => setEmailGoal(e.target.value)} placeholder={tx("邮件目标（如：约演示会议）")} className="form-input flex-1 min-w-[120px] sm:min-w-[160px] text-xs" />
        <button onClick={handleAIDraft} disabled={aiDrafting || !toName} className="flex items-center gap-1.5 rounded-lg bg-accent px-4 py-1.5 text-xs font-semibold text-white hover:bg-accent-hover disabled:opacity-50">
          {aiDrafting ? <Loader2 className="h-3.5 w-3.5 animate-spin" /> : <Sparkles className="h-3.5 w-3.5" />}
          {aiDrafting ? 'AI 草拟中...' : 'AI 草拟邮件'}
        </button>
      </div>

      {/* Body */}
      <div className="rounded-xl border border-border bg-card p-4">
        <textarea value={body} onChange={e => setBody(e.target.value)} placeholder={'邮件正文...\n\n提示：选择收件人后点击「AI 草拟邮件」，AI 会根据联系人的沟通偏好和心理画像定制邮件内容。'} rows={12} className="w-full resize-none border-0 bg-transparent text-sm text-foreground outline-none placeholder:text-muted" />
      </div>

      {/* Social intent */}
      {socialIntent && <SocialIntentPanel summary={socialIntent} compact />}

      {/* Sending advice */}
      {sendingAdvice && <div className="rounded-xl border border-accent/20 bg-accent/5 p-3">
          <p className="text-[12px] font-semibold text-accent mb-1">{tx("发送建议")}</p>
          <p className="text-xs text-secondary whitespace-pre-line">{sendingAdvice}</p>
        </div>}

      {/* Actions */}
      <div className="flex justify-between">
        <button onClick={handleCopy} className="flex items-center gap-1.5 rounded-lg border border-border px-4 py-2 text-sm text-foreground hover:bg-background">
          {copied ? <Check className="h-4 w-4 text-positive" /> : <Copy className="h-4 w-4" />}
          {copied ? '已复制' : '复制到剪贴板'}
        </button>
        <button onClick={handleSend} disabled={!toEmail || !body} className="flex items-center gap-1.5 rounded-lg bg-accent px-6 py-2 text-sm font-semibold text-white hover:bg-accent-hover disabled:opacity-50">
          <Send className="h-4 w-4" />{tx("发送（复制并记录）")}</button>
      </div>
    </div>;
}
export default function ComposePage() {
  const {
    locale
  } = useLocale();
  const en = locale === "en";
  const tx = (value: string) => en ? visibleBusinessText(value, "en") : value;
  return <Suspense fallback={<div className="p-6 text-muted">{tx("加载中...")}</div>}>
      <ComposeInner />
    </Suspense>;
}